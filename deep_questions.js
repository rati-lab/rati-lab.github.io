    s.focus = a[2] === 3 ? (a[1] === 3 ? "정리(④ × DQ1=이별후)" : "새 시작(④ × DQ1≠이별후)")
            : ["탐구(①)", "반복 원인(②)", "지금 지키기(③)"][a[2]];
    // 섹션 매핑: 시작 DQ4~7→06 / 운영 DQ8~10→07 / 표현·돌봄 DQ22~24→15·14 / 끌림 DQ25~27→10 / 이별 DQ28~31(+DQ3 게이트)→13 / 앵커 DQ1·2·32
    s.sections = { s06: [a[4],a[5],a[6],a[7]], s07: [a[8],a[9],a[10]], s15_14: [a[22],a[23],a[24]],
                   s10: [a[25],a[26],a[27]], s13: { gate_exp: a[3], answers: [a[28],a[29],a[30],a[31]] },
                   anchor: { state: a[1], focus: a[2], temp32: a[32] } };
